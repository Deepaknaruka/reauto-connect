-- 1. Enable UUID Extension
create extension if not exists "uuid-ossp";

-- 2. Profiles Table (stores user details linked to auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text default 'Rider',
  phone text,
  city text default 'Alwar, Rajasthan',
  role text default 'customer' check (role in ('customer', 'technician', 'admin')),
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 3. Vehicles Table (stores user's EV specifications)
create table if not exists public.vehicles (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid references auth.users(id) on delete cascade not null,
  brand text not null,
  model text not null,
  registration_number text,
  vehicle_type text default 'Scooter',
  battery_percentage integer check (battery_percentage between 0 and 100),
  is_primary boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 4. Technicians Table (stores verified EV technicians & their live status)
create table if not exists public.technicians (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid references auth.users(id) on delete set null,
  name text not null default 'Rakesh Sharma',
  phone text default '+91 98765 43210',
  rating numeric(3,2) default 4.80,
  is_online boolean default true,
  current_lat numeric(10,6) default 27.366350,
  current_lng numeric(10,6) default 76.679080,
  total_completed_jobs integer default 14,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 5. Service Requests Table (Roadside emergencies & planned EV services)
create table if not exists public.service_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  customer_name text default 'Rider',
  customer_phone text,
  type text not null, -- 'Battery', 'Charging', 'Motor', 'General EV Service', etc.
  kind text not null default 'Emergency', -- 'Emergency' or 'Service'
  status text not null default 'Finding Technician', -- 'Finding Technician' | 'Technician Assigned' | 'On The Way' | 'Arrived' | 'Completed' | 'Cancelled'
  description text,
  lat text default '27.34835',
  lng text default '76.69308',
  technician_id uuid references public.technicians(id) on delete set null,
  technician_name text,
  technician_phone text,
  technician_rating numeric(3,2) default 4.80,
  technician_lat numeric(10,6),
  technician_lng numeric(10,6),
  technician_eta integer default 12,
  total_price numeric(10,2) default 0,
  services_selected jsonb default '[]'::jsonb,
  declined_by_tech boolean default false,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 6. Indexes for ultra-fast queries
create index if not exists idx_requests_status on public.service_requests(status);
create index if not exists idx_requests_user on public.service_requests(user_id);
create index if not exists idx_requests_created on public.service_requests(created_at desc);
create index if not exists idx_vehicles_user on public.vehicles(user_id);

-- 7. Trigger to automatically create profile when user signs up
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', split_part(new.email, '@', 1))
  )
  on conflict (id) do update
  set email = excluded.email;
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 8. Trigger to update updated_at on records
create or replace function public.handle_updated_at()
returns trigger as $$
begin
  new.updated_at = timezone('utc'::text, now());
  return new;
end;
$$ language plpgsql;

drop trigger if exists set_updated_at_profiles on public.profiles;
create trigger set_updated_at_profiles before update on public.profiles
  for each row execute function public.handle_updated_at();

drop trigger if exists set_updated_at_vehicles on public.vehicles;
create trigger set_updated_at_vehicles before update on public.vehicles
  for each row execute function public.handle_updated_at();

drop trigger if exists set_updated_at_service_requests on public.service_requests;
create trigger set_updated_at_service_requests before update on public.service_requests
  for each row execute function public.handle_updated_at();

-- 9. Row Level Security (RLS) Configuration
alter table public.profiles enable row level security;
alter table public.vehicles enable row level security;
alter table public.technicians enable row level security;
alter table public.service_requests enable row level security;

-- Drop previous policies if re-running
drop policy if exists "Profiles read policy" on public.profiles;
drop policy if exists "Profiles update policy" on public.profiles;
drop policy if exists "Profiles insert policy" on public.profiles;

drop policy if exists "Vehicles read policy" on public.vehicles;
drop policy if exists "Vehicles write policy" on public.vehicles;

drop policy if exists "Technicians read policy" on public.technicians;
drop policy if exists "Technicians write policy" on public.technicians;

drop policy if exists "Requests read policy" on public.service_requests;
drop policy if exists "Requests insert policy" on public.service_requests;
drop policy if exists "Requests update policy" on public.service_requests;

-- Profiles: Anyone can view their own profile; authenticated users can read basic profiles
create policy "Profiles read policy" on public.profiles
  for select using (true);

create policy "Profiles update policy" on public.profiles
  for update using (auth.uid() = id or auth.role() = 'anon');

create policy "Profiles insert policy" on public.profiles
  for insert with check (auth.uid() = id or auth.role() = 'anon');

-- Vehicles: User owns vehicle or demo anon access
create policy "Vehicles read policy" on public.vehicles
  for select using (auth.uid() = user_id or auth.role() = 'anon');

create policy "Vehicles write policy" on public.vehicles
  for all using (auth.uid() = user_id or auth.role() = 'anon');

-- Technicians: Publicly readable; updates by technician or anon demo
create policy "Technicians read policy" on public.technicians
  for select using (true);

create policy "Technicians write policy" on public.technicians
  for all using (true);

-- Service Requests: Customers and technicians can create, read, and manage jobs
create policy "Requests read policy" on public.service_requests
  for select using (true);

create policy "Requests insert policy" on public.service_requests
  for insert with check (true);

create policy "Requests update policy" on public.service_requests
  for update using (true);

-- 10. Enable Supabase Realtime for instant customer & technician updates
alter publication supabase_realtime add table public.service_requests;
alter publication supabase_realtime add table public.technicians;

